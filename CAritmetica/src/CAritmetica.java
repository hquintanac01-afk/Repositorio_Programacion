public class CAritmetica {
    /**
     * @author Hugo Quintana Chamorro
     * Operaciones Aritmeticas
     * @param args the command line arguments
     */
    public static void main(String[] args) {
        int dato1; //Decalro la variable entera dato1
        int dato2; //Declaro, a la vez, dos variables enteras: dato2 y resultado
        int dato3, resultado;
        
        dato1 = 30; //Asigno el valor 20 a la variable dato1
        dato2 = 20;
        dato3 = 10;
        
        //Suma
        resultado = dato1 + dato2; //Guarda la suma de las dos variables en la variable resultado 
        System.out.println(dato1 + " + " + dato2 + " = " + resultado); // El metedo print escribe por panatalla tanto el valor de las variables asi como las cadenas que están entre comillas. Para unir los 5 elementos se ha utilizado el operador + */
        
        //Resta
        resultado = dato1 - dato2;
        System.out.println(dato1 + " - " + dato2 + " = " + resultado);
 
        
        //Suma
        resultado = dato1 + dato2 + dato3;
        System.out.println(dato1 + "+" + dato2 + "+" + dato3 + "=" + resultado);
        
        //Resta
        resultado = dato1 - dato2 - dato3;
        System.out.println(dato1 + "-" + dato2 + "-" + dato3 + "=" + resultado);
        
        //Multipiclación 
        resultado = dato1 * dato2 * dato3;
        System.out.println(dato1 + "*" + dato2 + "*" + dato3 + "=" + resultado);
        
        
    }
        
        
        
        
        
    }
    

